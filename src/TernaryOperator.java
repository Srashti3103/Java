
public class TernaryOperator {

	public static void main(String[] args) {
		/*
		 * A shortland for  if-else statement 
		 * operator : ? :
		 * 
		 * Syntax :
		 *  condition ? expression1 : expression2
		 */
		int age =18;
		String status = (age >= 18)?"Adult":"Minor";
		System.out.println(status);//Adult
	}

}
