
public class ShiftOperator {

	public static void main(String[] args) {
		/*
		 * used to shift the bits of a number left or right 
		 * operators <<,>>,>>>
		 * 
		 */
		int g=8;//Binary:1000
		System.out.println(g<<1);//Leftshift : 16 (10000)
		System.out.println(g>>1);//Right shift : 4 (0100)
		System.out.println(g>>>1);//Unsigned Right Shift : 4 (0100)
		
	}
}
